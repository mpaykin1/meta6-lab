#!/usr/bin/env python3
"""Add pinned MIT Blockwild TypeScript edition as an actual Voxel Game Creator runtime.

- Real game is cloned or copied unchanged from upstream.
- User's voxel RLE models are rendered in its existing THREE.Scene.
- Optional embedded GLBs load via Three's GLTFLoader (no extra canvas or renderer).
- No claimed physics/simulation synchronization with Lumenwild, Voxelize, Luanti.
"""

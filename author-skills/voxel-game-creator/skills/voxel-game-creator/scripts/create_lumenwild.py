#!/usr/bin/env python3
"""Build an original single-player browser game from the MIT Lumenwild source.

This generator retains terrain, caves, crafting, weather, mobile controls and
save systems; it changes visual design without exchanging engine internals.
"""
from __future__ import annotations
import argparse
import html
import json
import re
from pathlib import Path

from create_game import SCHEMES, fail, prepare_source as _voxelize_prepare_source, replace_once, run, save
import shutil

REPO = 'https://github.com/Vincent-P-essy/minecraft-clone.git'
PIN = '593eddaf542a563c1e9c857d42239be1d5002335'
BLOCK_ORIG = {'ground': (80, 142, 54), 'stone': (124, 124, 130), 'wood': (98, 70, 42), 'leaves': (56, 114, 42)}


def prepare_source(out: Path, source: Path | None, ref: str) -> None:
    if out.exists():
        fail(f'output already exists (will not overwrite): {out}')
    if source is not None:
        if not (source / 'src/render/tile-painter.ts').is_file() or not (source/'LICENSE').is_file():
            fail('--source must point to the original Lumenwild repository root with LICENSE')
        shutil.copytree(source, out, ignore=shutil.ignore_patterns('.git', 'node_modules', 'dist', '.cache', 'coverage'))
    else:
        if not shutil.which('git'):
            fail('git is required to obtain Lumenwild')
        run('git', 'clone', REPO, str(out))
        if ref:
            run('git', 'checkout', '--detach', ref, cwd=out)
    license_text = (out/'LICENSE').read_text(encoding='utf-8') if (out/'LICENSE').exists() else ''
    if not license_text.startswith('MIT License'):
        fail('Lumenwild MIT LICENSE missing; cannot continue')


def color_rgb(value: str) -> tuple[int, int, int]:
    if not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
        fail(f'invalid hex color: {value}')
    return tuple(int(value[i:i+2], 16) for i in (1, 3, 5))


def fmt_rgb(rgb: tuple[int, int, int]) -> str:
    return ', '.join(str(x) for x in rgb)


def linear(value: str) -> str:
    comps = []
    for n in color_rgb(value):
        c = n / 255
        comps.append(round(c/12.92 if c <= .04045 else ((c+.055)/1.055)**2.4, 5))
    return '['+', '.join(str(v) for v in comps)+']'


def ts_palette(colors: dict[str, str]) -> str:
    """Shared tint for Lumenwild's GL texture array AND HUD mini-atlas.

    Leaves tile opacity/alpha and animation alone. All 16x16 tile pixels keep
    contrast and transparent holes, so foliage cutouts remain valid.
    """
    pairs = [
      ('GRASS_TOP','ground'),('GRASS_SIDE','ground'),('TALL_GRASS','ground'),
      ('STONE','stone'),('COBBLE','stone'),('STONE_BRICK','stone'),('GRAVEL','stone'),
      ('WOOD_SIDE','wood'),('WOOD_TOP','wood'),('PLANKS','wood'),
      ('PINE_WOOD_SIDE','wood'),('PINE_WOOD_TOP','wood'),
      ('LEAVES','leaves'),('PINE_LEAVES','leaves'),('AUTUMN_LEAVES','leaves'),
    ]
    entries=[]
    for tile,key in pairs:
        target=color_rgb(colors[key]); base=BLOCK_ORIG[key]
        entries.append(f'  [TileKind.{tile}]: {{ base: [{fmt_rgb(base)}], target: [{fmt_rgb(target)}] }},')
    return '''// Generated by Voxel Game Creator. MIT upstream shader/texture engine preserved.
import { TileKind } from '../render/atlas-layout';
type RGB = readonly [number, number, number];
const TINTS: Partial<Record<TileKind, { base: RGB; target: RGB }>> = {
'''+ '\n'.join(entries)+ '''
};
// Tint modifies RGB alone; retains alpha (emissive/cutout semantics).
export function tintVoxelTile(tile: TileKind, pixels: Uint8ClampedArray): void {
  const spec = TINTS[tile];
  if (!spec) return;
  const baseLum = Math.max(1, spec.base[0]*.25 + spec.base[1]*.6 + spec.base[2]*.15);
  for (let i = 0; i < pixels.length; i += 4) {
    if (pixels[i+3] === 0) continue;
    const lum = (pixels[i]*.25 + pixels[i+1]*.6 + pixels[i+2]*.15) / baseLum;
    const shade = Math.max(.3, Math.min(1.65, lum));
    for (let c = 0; c < 3; c++) {
      pixels[i+c] = Math.max(0, Math.min(255, Math.round(
        (spec.target[c] * .82 + pixels[i+c] * .18) * shade
      )));
    }
  }
}
'''


def apply_theme(out: Path, title: str, theme: str, seed: int, colors: dict[str,str]):
    brand = out / 'src/branding.ts'
    txt=brand.read_text(encoding='utf-8')
    txt=replace_once(txt, 'export const GAME_NAME = "Lumenwild";', 'export const GAME_NAME = '+json.dumps(title,ensure_ascii=False)+';', 'brand name')
    txt=replace_once(txt, 'export const GAME_TAGLINE = "An endless world of light, built block by block.";',
          'export const GAME_TAGLINE = '+json.dumps('Исследуй, строй, оставь свой след.',ensure_ascii=False)+';', 'tagline')
    save(brand,txt)

    main=out/'src/main.ts'; txt=main.read_text(encoding='utf-8')
    txt=replace_once(txt,'const DEFAULT_SEED = 2026;',f'const DEFAULT_SEED = {seed};','default seed')
    save(main,txt)

    render=out/'src/render/environment.ts'; txt=render.read_text(encoding='utf-8')
    substitutions={
      'ZENITH_DAY': colors['top'],'HORIZON_DAY':colors['horizon'],
      'ZENITH_DUSK':colors['top'],'HORIZON_DUSK':colors['sunset'],
      'ZENITH_NIGHT':colors['night'],'HORIZON_NIGHT':colors['night'],
    }
    for key,value in substitutions.items():
        pattern = rf'(?m)^(const {key}: Vec3Tuple = )\[[^\]\n]+\](;)$'
        txt,n=re.subn(pattern,lambda m:m.group(1)+linear(value)+m.group(2),txt)
        if n!=1:fail(f'Lumenwild environment upstream anchor {key}: expected exactly once, got {n}')
    save(render,txt)

    sky=out/'src/render/sky.ts'; txt=sky.read_text(encoding='utf-8')
    by_phase={'0.0':colors['sunset'],'0.1':colors['horizon'],'0.45':colors['horizon'],
      '0.55':colors['sunset'],'0.62':colors['top'],'0.75':colors['night'],
      '0.92':colors['night'],'1.0':colors['sunset']}
    for phase,value in by_phase.items():
        pattern=rf'(?m)(\{{ phase: {re.escape(phase)}, sky: )\[[^\]]+\]'
        txt,n=re.subn(pattern,lambda m:m.group(1)+'['+fmt_rgb(color_rgb(value))+']',txt)
        if n!=1:fail(f'sky phase {phase} anchor absent or duplicate ({n})')
    save(sky,txt)

    painter=out/'src/render/tile-painter.ts'; txt=painter.read_text(encoding='utf-8')
    txt=replace_once(txt,'import { ATLAS_TILE_SIZE, TileKind } from "./atlas-layout";',
         'import { ATLAS_TILE_SIZE, TileKind } from "./atlas-layout";\nimport { tintVoxelTile } from "../vgc/theme";', 'tile painter imports')
    txt=replace_once(txt,'  bleedCutout(canvas);\n  return canvas.data;',
         '  bleedCutout(canvas);\n  tintVoxelTile(tile, canvas.data);\n  return canvas.data;', 'tile painter tint')
    save(painter,txt)
    (out/'src/vgc').mkdir(exist_ok=True)
    save(out/'src/vgc/theme.ts',ts_palette(colors))

    # CPU fallback is tinted too; this is important for devices without WebGL2.
    cpu=out/'src/render/block-colors.ts'; txt=cpu.read_text(encoding='utf-8')
    for block,base,new in [
      ('GRASS',BLOCK_ORIG['ground'],colors['ground']),
      ('STONE',BLOCK_ORIG['stone'],colors['stone']),
      ('DIRT',(116,82,52),colors['ground']),
      ('LEAVES',BLOCK_ORIG['leaves'],colors['leaves']),
      ('PLANKS',(174,134,80),colors['wood']),
      ('COBBLE',(120,120,126),colors['stone']),
    ]:
      if block=='GRASS':
        old='[BlockId.GRASS]: { top: [80, 142, 54], side: [116, 82, 52] },'
        new_txt=f'[BlockId.GRASS]: {{ top: [{fmt_rgb(color_rgb(new))}], side: [{fmt_rgb(color_rgb(colors["ground"]))}] }},'
      else:
        old=f'[BlockId.{block}]: uniform({fmt_rgb(base)}),'
        new_txt=f'[BlockId.{block}]: uniform({fmt_rgb(color_rgb(new))}),'
      txt=replace_once(txt,old,new_txt,f'CPU color {block}')
    old='[BlockId.WOOD]: { top: [170, 134, 86], side: [98, 70, 42] },'
    new='[BlockId.WOOD]: { top: ['+fmt_rgb(color_rgb(colors['wood']))+'], side: ['+fmt_rgb(color_rgb(colors['wood']))+'] },'
    txt=replace_once(txt,old,new,'CPU color WOOD')
    save(cpu,txt)

    index=out/'index.html'; txt=index.read_text(encoding='utf-8')
    label=html.escape(title)
    txt=replace_once(txt,'<title>Lumenwild</title>',f'<title>{label}</title>','HTML browser title')
    txt=replace_once(txt,'<h1 class="title">Lumenwild</h1>',f'<h1 class="title">{label}</h1>','HTML menu heading')
    save(index,txt)
    # Give the PWA its own identity while retaining the original icon art.
    manifest=out/'public/manifest.webmanifest'
    if manifest.is_file():
        obj=json.loads(manifest.read_text(encoding='utf-8'))
        obj['name']=title
        obj['short_name']=title[:24]
        obj['description']='Авторский воксельный мир для исследования и строительства.'
        save(manifest,json.dumps(obj,ensure_ascii=False,indent=2)+'\n')

    # Lumenwild defaults to a repo-specific GitHub Pages base. Relative
    # assets are essential for arbitrary names and nested hosted paths.
    vite=out/'vite.config.ts'; txt=vite.read_text(encoding='utf-8')
    txt=replace_once(txt,
        'base: process.env.GITHUB_PAGES ? "/minecraft-clone/" : mode === "native" ? "./" : "/",',
        'base: "./",', 'portable nested-path static hosting')
    save(vite,txt)
    # Preserve source LICENSE and the original world/player/input/mesh systems.
    save(out/'VOXEL_GAME.json',json.dumps({
      'title':title,'theme':theme,'seed':seed,'colors':colors,'engine':'browser',
      'source':REPO,'source_ref':PIN,
      'features':['terrain','caves','weather','build','survival crafting','touch','controller','saves'],
      'multiplayer':False
    },ensure_ascii=False,indent=2)+'\n')
    script='''#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
command -v npm >/dev/null || { echo 'Node.js/npm required' >&2; exit 2; }
npm ci
npm run dev -- --host 0.0.0.0
'''
    save(out/'run-voxel-game.sh',script)
    (out/'run-voxel-game.sh').chmod(0o755)
    print(f'CREATED browser game {out}. Build: cd {out} && npm ci && npm run build')


def game(spec: dict, target: Path, source: Path | None, ref: str=PIN):
    title=spec.get('title','Voxel World'); theme=spec.get('theme','ash'); seed=spec.get('seed',7391)
    if not isinstance(title,str) or not 1 <= len(title) <= 80:fail('invalid title')
    if theme not in SCHEMES:fail('invalid theme')
    if isinstance(seed,bool) or not isinstance(seed,int) or not 1 <= seed <= 2147483647:fail('invalid seed')
    colors=dict(SCHEMES[theme]); overrides=spec.get('colors',{})
    if not isinstance(overrides,dict):fail('colors must be dictionary')
    for key,value in overrides.items():
        if key not in colors or not isinstance(value,str) or not re.fullmatch(r'#[0-9a-fA-F]{6}',value):fail('invalid color override '+str(key))
        colors[key]=value
    target=target.resolve();target.parent.mkdir(parents=True,exist_ok=True)
    prepare_source(target,source,ref)
    apply_theme(target,title,theme,seed,colors)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--spec',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    p.add_argument('--source',type=Path)
    p.add_argument('--ref',default=PIN)
    args=p.parse_args()
    try:spec=json.loads(args.spec.read_text(encoding='utf-8'))
    except (OSError,ValueError) as e:fail(str(e))
    game(spec,args.out,args.source,args.ref)
if __name__=='__main__':main()

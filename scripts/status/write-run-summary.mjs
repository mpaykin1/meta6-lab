import fs from 'node:fs';
const [s='failure',jobArg='checks',repo,runId,summaryFile]=process.argv.slice(2);
if(!repo||!runId||!summaryFile)throw Error('Missing required workflow arguments');
const state=s==='success'?'зелёный':'красный';
const job=jobArg.replace(/[\r\n|]/g,' ').slice(0,90);
const url='https://github.com/'+repo+'/actions/runs/'+runId;
const lines=['status: '+state,'workflow/job: '+job,'first_error: '+(s==='success'?'нет':'ошибка в шаге '+job+' (полный лог Actions)'),'run: '+url];
fs.mkdirSync('reports',{recursive:true});
fs.writeFileSync('reports/LAST_RUN.md',lines.join('\n')+'\n');
fs.appendFileSync(summaryFile,lines.join('\n')+'\n');
console.log(lines.join(' | '));
